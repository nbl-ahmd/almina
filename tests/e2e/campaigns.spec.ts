import { mkdir } from 'node:fs/promises';
import { test, expect, reset, login, adminOrigin, commerceOrigin, productId } from './fixtures';

for (const width of [390, 1280]) test(`staff can preview, review and place a campaign at ${width}px`, async ({ page, request }) => {
  await mkdir('outputs/campaign-merchandising-2026-10-20',{recursive:true});
  await reset(request);
  await page.setViewportSize({ width, height: 900 });
  await page.route('**/_next/image?**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="400"><rect width="800" height="400" fill="#e9edff"/></svg>' }));
  await login(page);
  await page.goto(adminOrigin + '/admin/growth');
  await page.getByRole('combobox', { name: 'Page type', exact: true }).selectOption('campaign');
  await page.getByRole('textbox', { name: /^URL name/ }).fill('synthetic-care');
  await page.getByLabel('Title', { exact: true }).fill('Synthetic care campaign');
  await page.getByLabel('Search description', { exact: true }).fill('A useful selection of available personal care products.');
  await page.getByLabel('Page content', { exact: false }).fill('Compare the current products and choose the pack that suits your routine.');
  await page.getByLabel('Desktop artwork URL', { exact: true }).fill('https://cdn.alminapharmacy.com/cdn/synthetic/desktop.webp');
  await page.getByLabel('Image description', { exact: true }).fill('Synthetic care selection');
  await page.getByLabel('Phone artwork URL', { exact: true }).fill('https://cdn.alminapharmacy.com/cdn/synthetic/mobile.webp');
  await page.getByRole('combobox', { name: 'Homepage position', exact: true }).selectOption('hero');
  await page.getByRole('spinbutton', { name: /^Display priority/ }).fill('75');
  // Text over the artwork's safe zone; the default 'Finished image only' layout shows artwork alone.
  await page.getByRole('combobox', { name: 'Carousel layout', exact: false }).selectOption('overlay');
  await page.getByLabel('Campaign button text', { exact: true }).fill('Explore synthetic care');
  await page.getByLabel('Campaign terms', { exact: true }).fill('Current prices apply. While stock is available. No additional discount.');
  await page.getByRole('button', { name: 'Mobile', exact: true }).click();
  const preview = page.locator('section[aria-labelledby="campaign-merchandising-title"]');
  await expect(preview.getByRole('img', { name: 'Synthetic care selection' })).toHaveAttribute('src', /mobile/);
  await page.getByRole('button', { name: 'Check campaign readiness', exact: true }).click();
  await expect(page.getByText('No products are pinned.', { exact: false })).toBeVisible();
  await page.locator('summary').filter({hasText:'Maintenance tools'}).click();
  await page.getByRole('button', { name: 'Refresh search suggestions', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: /Search index:/ })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Related products', exact: false }).fill('Synthetic care');
  await page.getByRole('button', { name: /Synthetic care product.*Add/ }).click();
  await page.getByRole('button', { name: 'Check campaign readiness', exact: true }).click();
  await expect(page.getByText('Synthetic care product has no product photo.', { exact: true })).toBeVisible();
  await preview.scrollIntoViewIfNeeded();
  await page.screenshot({path:`outputs/campaign-merchandising-2026-10-20/editor-${width}.png`});
  await page.getByLabel('Publish this page', { exact: true }).check();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Saved. Published pages appear' })).toBeVisible();
  const rows = await page.request.get(adminOrigin + '/api/growth/campaigns?locale=en');
  expect(rows.status()).toBe(200);
  const body = await rows.json(); expect(body.data[0].productIds).toEqual([productId]); expect(body.data[0].priority).toBe(75);
  await page.goto(adminOrigin + '/');
  await expect(page.getByRole('heading', { name: 'Synthetic care campaign', exact: true })).toBeVisible();
  await page.screenshot({path:`outputs/campaign-merchandising-2026-10-20/home-${width}.png`});
  await page.getByRole('link', { name: 'Explore synthetic care', exact: true }).click();
  await expect(page).toHaveURL(adminOrigin + '/offers/synthetic-care');
  await expect(page.getByRole('heading', { name: 'Synthetic care campaign', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Synthetic care product', exact: true })).toBeVisible();
  await page.reload();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await request.get(commerceOrigin + '/__fixture/state')).ok()).toBeTruthy();
});
