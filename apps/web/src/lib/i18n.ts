export const messages: Record<Locale, Record<MessageKey, string>> = { en, ar };
export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}
/** Replaces `{name}` placeholders so a locale can reorder them. Unknown placeholders are left intact. */
export function tf(locale: Locale, key: MessageKey, values: Record<string, string | number>): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}
